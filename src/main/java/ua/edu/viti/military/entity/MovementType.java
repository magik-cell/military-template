package ua.edu.viti.military.entity;

/**
 * Типи операцій з персоналом
 */
public enum MovementType {
    ASSIGNMENT,     // Призначення на посаду
    TRANSFER,       // Переведення (між підрозділами або посадами)
    PROMOTION,      // Підвищення звання
    DISMISSAL,      // Звільнення
    LEAVE,          // Відпустка
    DEPLOYMENT      // Відрядження/Командування
}
